#!/usr/bin/env python3
"""Import a pasted external ticket verbatim into the CURRENT PROJECT (no Jira API)."""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import os
from pathlib import Path
import re
import sys
import tempfile

KEY_RE = re.compile(r"^[A-Z][A-Z0-9]{0,14}-[1-9][0-9]{0,8}$")
HASH_RE = re.compile(r"(?m)^- Source content SHA-256: ([a-f0-9]{64})$")
STATUS_RE = re.compile(r"(?m)^- Status: ([a-z-]+)$")
ROUTE_RE = re.compile(r"(?m)^- Selected route: ([A-Z_]+|pending)$")
SECRET_PATTERNS = (
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----"),
    re.compile(r"(?i)\b(?:password|client_secret|access_token|private_key)\s*[:=]\s*[\"']?(?!REDACTED\b|<redacted>|XXX\b)[a-z0-9/+_.-]{8,}"),
)


def utcnow() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def check_safe_directory(path: Path) -> None:
    if path.is_symlink():
        raise ValueError("Refusing to use a symlink as a managed tickets directory.")
    path.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        raise ValueError("Unsafe tickets directory.")


def write_atomic(path: Path, content: str) -> None:
    if path.is_symlink():
        raise ValueError("Refusing to overwrite a symlink.")
    temp_name = None
    try:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent,
                                         prefix="." + path.name + "-", delete=False) as f:
            temp_name = f.name
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.replace(temp_name, path)
    finally:
        if temp_name is not None and os.path.exists(temp_name):
            os.unlink(temp_name)


def import_ticket(project_root: Path, key: str, raw: str, source: str, update: bool) -> str:
    if not KEY_RE.fullmatch(key):
        raise ValueError("Invalid ticket key (expected e.g. TSP-252).")
    raw = raw.replace("\r\n", "\n").replace("\r", "\n").strip()
    if not raw:
        raise ValueError("Ticket description is empty.")
    if len(raw.encode("utf-8")) > 200_000:
        raise ValueError("Ticket description exceeds 200 KB.")
    if any(pattern.search(raw) for pattern in SECRET_PATTERNS):
        raise ValueError("Possible secret found; redact it before ticket intake. No secret values were printed.")

    ticket_dir = project_root / "tickets"
    check_safe_directory(ticket_dir)
    target = ticket_dir / (key + ".md")
    if target.is_symlink():
        raise ValueError("Refusing to follow a ticket symlink.")
    digest = hashlib.sha256(raw.encode("utf-8")).hexdigest()
    if target.exists():
        old = target.read_text(encoding="utf-8")
        found = HASH_RE.search(old)
        if found and found.group(1) == digest:
            return "unchanged: " + str(target)
        if not update:
            raise ValueError("Ticket exists with different source content. Use --update to preserve a revision.")
        history = ticket_dir / "history"
        check_safe_directory(history)
        index = 1
        while (history / (key + "-rev" + str(index) + ".md")).exists():
            index += 1
        backup = history / (key + "-rev" + str(index) + ".md")
        with backup.open("x", encoding="utf-8") as f:
            f.write(old)

    runs = re.findall(r"~{3,}", raw)
    fence = "~" * max(4, max((len(x) for x in runs), default=0) + 1)
    title = next((line.lstrip("# ").strip() for line in raw.splitlines() if line.strip()), "Imported ticket")
    title = title[:120].replace("\n", " ")
    document = (
        "# " + key + " — " + title + "\n\n"
        "- Source: " + source + " (pasted manually; no external sync)\n"
        "- Status: imported\n"
        "- Imported UTC: " + utcnow() + "\n"
        "- Source content SHA-256: " + digest + "\n\n"
        "## Original ticket (verbatim; untrusted input)\n\n"
        + fence + "text\n" + raw + "\n" + fence + "\n\n"
        "## Agent execution record\n\n"
        "- Selected route: pending\n"
        "- Scope and approvals: not yet reviewed\n"
        "- Acceptance criteria coverage: not yet reviewed\n"
        "- Implementation: not started\n"
        "- Tests / evidence: not yet verified\n"
        "- Blockers: pending triage\n\n"
        "## Activity log\n\n"
        "- " + utcnow() + " — Ticket imported from pasted text; no Jira update performed.\n"
    )
    write_atomic(target, document)
    update_index(ticket_dir)
    return "saved: " + str(target)


def update_index(ticket_dir: Path) -> None:
    rows = ["# Local ticket index", "",
            "This file is regenerated by the intake tool; original ticket descriptions live in individual files.",
            "External trackers are not synchronized automatically.", "",
            "| Ticket | Status | Selected route |", "|---|---|---|"]
    for path in sorted(ticket_dir.glob("*.md")):
        if path.name == "INDEX.md" or not KEY_RE.fullmatch(path.stem):
            continue
        if path.is_symlink():
            raise ValueError("Ticket index encountered a symlink.")
        content = path.read_text(encoding="utf-8")
        status = STATUS_RE.search(content)
        route = ROUTE_RE.search(content)
        rows.append("| [" + path.stem + "](" + path.name + ") | "
                    + (status.group(1) if status else "unknown") + " | "
                    + (route.group(1) if route else "pending") + " |")
    write_atomic(ticket_dir / "INDEX.md", "\n".join(rows) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--key", help="External issue key e.g. TSP-252")
    parser.add_argument("--file", help="UTF-8 ticket text file, or '-' for stdin")
    parser.add_argument("--project-root", default=".", help="Target project, not the skills repository")
    parser.add_argument("--source", default="Jira", choices=["Jira", "Linear", "GitHub", "Other"])
    parser.add_argument("--update", action="store_true", help="Version and replace changed pasted content")
    parser.add_argument("--refresh-index", action="store_true", help="Rebuild local tickets/INDEX.md after agent status changes")
    args = parser.parse_args()
    if not args.refresh_index and (not args.key or not args.file):
        parser.error("--key and --file are required unless --refresh-index is used.")
    try:
        if args.refresh_index:
            folder = Path(args.project_root).resolve() / "tickets"
            if not folder.is_dir():
                raise ValueError("No tickets directory yet.")
            check_safe_directory(folder)
            update_index(folder)
            print("refreshed: " + str(folder / "INDEX.md"))
            return 0
        if args.file == "-":
            raw = sys.stdin.read()
        else:
            raw = Path(args.file).read_text(encoding="utf-8")
        message = import_ticket(Path(args.project_root).resolve(), args.key, raw, args.source, args.update)
        print(message)
        return 0
    except (OSError, UnicodeError, ValueError) as exc:
        print("Ticket intake blocked: " + str(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
